function buildProfileSnapshot(profile: RawFeyliProfile): ArticleSnapshot {
  const languagesText = profile.languages.join('، ');

  const infoboxRows: InfoboxRow[] = [
    { label: 'الاسم الكامل', value: profile.full_name },
    { label: 'الشهادة العلمية', value: profile.degree },
    { label: 'التخصص', value: profile.specialization },
    { label: 'المنصب / الدور الحالي', value: profile.current_role },
    { label: 'سنوات الخبرة', value: profile.experience_years },
    { label: 'اللغات', value: languagesText },
    { label: 'الاهتمام الرئيسي', value: profile.primary_interest }
  ];

  if (profile.locationNote) {
    infoboxRows.push({ label: 'نطاق النشاط', value: profile.locationNote });
  }

  const sections: ArticleSection[] = [
    {
      id: 'academic-career',
      title: 'التحصيل الأكاديمي والمسيرة المهنية',
      content: `تحمل السيرة الأكاديمية والمهنية لـ${profile.title} شهادة ${profile.degree} في تخصص ${profile.specialization}، مع خبرة عملية تمتد إلى ${profile.experience_years} في مجال ${profile.field}.[1]\nالدور الوظيفي والمؤسسي الحالي: ${profile.current_role}، مع اهتمام رئيسي ينصبّ على «${profile.primary_interest}»، وإجادة اللغات: ${languagesText}.[1]`
    },
    {
      id: 'roles-memberships',
      title: 'الأدوار والعضويات المؤسسية',
      content: [
        'تتوزع الأدوار المؤسسية والعضويات والمسؤوليات الموثقة ضمن المسيرة العملية والاجتماعية على المحاور الآتية:[1]',
        ...profile.memberships_and_roles.map((item) => `* ${item}`)
      ].join('\n')
    },
    {
      id: 'skills-contributions',
      title: 'المهارات والمساهمات المجتمعية',
      content: [
        'المهارات التخصصية الموثقة:',
        ...profile.skills.map((item) => `* ${item}`),
        'أبرز المساهمات والأنشطة المجتمعية والفكرية:[1]',
        ...profile.contributions.map((item) => `* ${item}`)
      ].join('\n')
    }
  ];

  if (profile.awards_and_certificates.length > 0) {
    sections.push({
      id: 'awards-certificates',
      title: 'التكريم والشهادات',
      content: [
        'حصلت خلال مسيرتها المهنية والأكاديمية على مجموعة من كتب الشكر والتكريمات الرسمية والشهادات التخصصية:[1]',
        ...profile.awards_and_certificates.map((item) => `* ${item}`)
      ].join('\n')
    });
  }

  return {
    name: profile.title,
    subtitle: profile.current_role,
    portal: 'شخصيات وأعلام',
    articleType: 'person',
    summary: `${profile.summary}[1]`,
    field: profile.field,
    activeYears: `خبرة ${profile.experience_years}`,
    birthDate: '',
    deathDate: '',
    birthDeath: '',
    birthplace: '',
    notableWorks: profile.notableWorks,
    infoboxRows,
    categories: profile.categories,
    subcategories: profile.subcategories,
    sections,
    references: [
      {
        id: 1,
        text: 'أرشيف ويكي فيلي — قاعدة بيانات السير الذاتية الموثقة للشخصيات الكوردية الفيلية (ملف السير الذاتية).'
      }
    ]
  };
}

